package com.kuma.cloud.lab.database;

import com.zaxxer.hikari.HikariDataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

final class DatabaseSupport implements AutoCloseable {
    final HikariDataSource source;
    private final LabDatabase database;

    DatabaseSupport() throws SQLException {
        database = LabDatabase.open("database", 4, 2000);
        source = database.source();
        try (Connection connection = connection()) {
            System.out.println("database=" + connection.getMetaData().getDatabaseProductName()
                    + ", version=" + connection.getMetaData().getDatabaseProductVersion());
            update(connection, "CREATE TABLE accounts(id INT PRIMARY KEY, owner VARCHAR(100) NOT NULL UNIQUE, balance DECIMAL(12,2) NOT NULL CHECK(balance>=0), version INT NOT NULL DEFAULT 0)");
            update(connection, "CREATE TABLE catalog(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, category VARCHAR(30), price DECIMAL(12,2) NOT NULL CHECK(price>=0))");
            update(connection, "CREATE TABLE sales(id INT PRIMARY KEY, item_id BIGINT NOT NULL REFERENCES catalog(id), qty INT NOT NULL CHECK(qty>0))");
            update(connection, "CREATE TABLE audit_log(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note VARCHAR(100) NOT NULL)");
            update(connection, "INSERT INTO accounts(id,owner,balance) VALUES(1,'Alice',100),(2,'Bob',50)");
        } catch (SQLException | RuntimeException | Error failure) {
            source.close(); throw failure;
        }
    }

    Connection connection() throws SQLException { return source.getConnection(); }
    @Override public void close() { database.close(); }

    static PreparedStatement prepare(Connection connection, String sql, Object... arguments) throws SQLException {
        PreparedStatement statement = connection.prepareStatement(sql);
        try {
            statement.setQueryTimeout(5);
            for (int i = 0; i < arguments.length; i++) statement.setObject(i + 1, arguments[i]);
            return statement;
        } catch (SQLException failure) { statement.close(); throw failure; }
    }
    static int update(Connection connection, String sql, Object... arguments) throws SQLException {
        try (var statement = prepare(connection, sql, arguments)) {
            int affected = statement.executeUpdate();
            System.out.println("SQL " + sql + " -> affected=" + affected);
            return affected;
        }
    }
    static List<Map<String, Object>> query(Connection connection, String sql, Object... arguments) throws SQLException {
        try (var statement = prepare(connection, sql, arguments); var rows = statement.executeQuery()) {
            var result = new ArrayList<Map<String, Object>>();
            var metadata = rows.getMetaData();
            while (rows.next()) {
                var row = new LinkedHashMap<String, Object>();
                for (int i = 1; i <= metadata.getColumnCount(); i++) row.put(metadata.getColumnLabel(i).toLowerCase(Locale.ROOT), rows.getObject(i));
                result.add(row);
            }
            System.out.println("SQL " + sql + " -> " + result);
            return result;
        }
    }
    static int number(Connection connection, String sql, Object... arguments) throws SQLException {
        try (var statement = prepare(connection, sql, arguments); var rows = statement.executeQuery()) {
            if (!rows.next()) throw new SQLException("Expected scalar result: " + sql);
            return rows.getBigDecimal(1).intValueExact();
        }
    }
    static List<Map<String, Object>> balances(Connection connection) throws SQLException {
        return query(connection, "SELECT id,owner,balance,version FROM accounts ORDER BY id");
    }
    static void check(String label, boolean condition, Object evidence) {
        System.out.println(label + " = " + evidence + "; check=" + condition);
        if (!condition) throw new IllegalStateException(label + ": " + evidence);
    }
    static void constraint(Connection connection, String sql, Object... arguments) throws SQLException {
        try { update(connection, sql, arguments); throw new AssertionError("Expected constraint rejection"); }
        catch (SQLException expected) {
            check("约束拒绝", expected.getSQLState() != null && expected.getSQLState().startsWith("23"),
                    "SQLState=" + expected.getSQLState() + ", errorCode=" + expected.getErrorCode());
        }
    }
}
